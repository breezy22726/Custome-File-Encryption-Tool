    private void forgotpasswordBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_forgotpasswordBtnActionPerformed
        // TODO add your handling code here:
        if (keys == null) {
        keys = new Keymanager("auth.dat");
    }
    
    // Check if an account even exists
    try {
        if (!keys.hasCredentials()) {
            JOptionPane.showMessageDialog(this, 
                "No registered account was found. Please sign up instead.", 
                "Account Not Found", 
                JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        // Prompt the user with a warning about local encryption recovery limits
        int choice = JOptionPane.showConfirmDialog(this, 
            "Because your security keys are encrypted locally, passwords cannot be recovered.\n\n" +
            "Would you like to reset your account?\n" +
            "(Warning: This will clear existing credentials and let you create a new sign-up).", 
            "Forgot Password / Reset Account", 
            JOptionPane.YES_NO_OPTION, 
            JOptionPane.WARNING_MESSAGE);

        if (choice == JOptionPane.YES_OPTION) {
            // Delete the local auth file to clear credentials
            java.io.File authFile = new java.io.File("auth.dat");
            if (authFile.exists()) {
                authFile.delete();
            }
            
            if (logger != null) {
                logger.log("Account reset initiated due to forgotten password.");
            }

            JOptionPane.showMessageDialog(this, 
                "Account data cleared successfully. Please create a new account.", 
                "Reset Complete", 
                JOptionPane.INFORMATION_MESSAGE);

            // Open the SignUp window and pass your shared dependencies
            SignUp signup = new SignUp(processor, keys, logger);
            signup.setVisible(true);
            this.dispose();
        }
        
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, 
            "Error handling password reset: " + ex.getMessage(), 
            "Error", 
            JOptionPane.ERROR_MESSAGE);
    }
        
    }//GEN-LAST:event_forgotpasswordBtnActionPerformed

