        private void authenticateUser(){
            if (keys == null) {
            keys = new Keymanager("auth.dat"); // Fallback safety initialization
        }

        String username = usernameTF2.getText().trim();
        char[] password = passwordTF2.getPassword(); // Works if passwordTF2 is JPasswordField
        
        try {
            if(!keys.hasCredentials()){
                JOptionPane.showMessageDialog(this, "No account was found. Please sign up.");
                return;
            }
            
            if(!keys.authenticate(username, password)){
                JOptionPane.showMessageDialog(this, "Incorrect username or password.");
                return;
            }
            
            sessionPassword = password.clone();
            JOptionPane.showMessageDialog(this, "Login successful!");
            
            // Pass all dependencies forward to the Dashboard
            Dashboard dashboard = new Dashboard(processor, keys, logger, sessionPassword);
            dashboard.setVisible(true);
            
            this.dispose();
        } catch (Exception ex){
            JOptionPane.showMessageDialog(this, "Login error: " + ex.getMessage());
        } /*finally {
            Arrays.fill(password, '\0');
        }*/
    }

