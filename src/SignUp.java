    private String createUsername(String fullname){
        
        String cleaned = fullname.trim().replaceAll("\\s+", " ");
        
        String[] parts = cleaned.split(" ");
        
        if(parts.length < 2){
            return null;
        }
        
        for (String part: parts){
            if(!part.matches("[A-Za-z]+(?:[\\'-][A-Za-z]+)*")){
                return null;
            }
        }
        
        StringBuilder name = new StringBuilder();
        
        for (String part : parts){
            name.append(part);
        }
        
        return name.toString() + "@encrypt";
    }
    
    
    private boolean validPassword(char[] password){
        
        if (password.length < 8){
            return false;
        }
        
        boolean letter = false;
        boolean digit = false;
        
        int special = 0;
        
        
        for (char ch : password){
            
            if(Character.isWhitespace(ch)){
                return false;
            }
            
            if(Character.isLetter(ch)){
                letter = true;
            } else if (Character.isDigit(ch)){
                digit = true;
            } else {
                
                special++;
            }
        }
        
        return letter && digit && special == 1;
    }
    
    
    private void registerAccount(){
        
        if (keys == null) {
            JOptionPane.showMessageDialog(this, "Keymanager not initialized.");
            return;
        }

        String fullName = usernameTF.getText().trim();
        char[] password = passwordField.getPassword();
        char[] confirmPassword = passwordField2.getPassword();
        
        try {
            String accountUsername = createUsername(fullName);
            
            if (accountUsername == null) {
                JOptionPane.showMessageDialog(this, "Enter your first name and surname. Use letters only.");
                return;
            }
            
            if(keys.hasCredentials()){
                JOptionPane.showMessageDialog(this, "An account already exists. Please log in.");
                return;
            }
            
            if(!validPassword(password)){
                JOptionPane.showMessageDialog(this, 
                        "Password must be at least 8 characters,\n" +
                        "include at least one letter and one number,\n" +
                        "contain exactly one special character,\n" +
                        "and have no spaces.");
                return;
            }
            
            if(!Arrays.equals(password, confirmPassword)){
                JOptionPane.showMessageDialog(this, "Passwords do not match.");
                return;
            }
            
            keys.registerAccount(accountUsername, password);
            if (logger != null) logger.log("Account created for " + accountUsername);
            
            JOptionPane.showMessageDialog(this, 
                    "Account created successfully!\nYour username is: " + accountUsername);
            
            // Return to login window
            LogIn login = new LogIn(processor, keys, logger);
            login.setVisible(true);
            this.dispose();
            
        } catch (Exception ex){
            JOptionPane.showMessageDialog(this, "Registration error: " + ex.getMessage());
        } finally {
            Arrays.fill(password, '\0');
            Arrays.fill(confirmPassword, '\0');
        }
    
        
    }

    
