    private void processFile(boolean encrypt){
        if (selectedFile == null) {
            alert("Please choose file first");
            return;
        }
        
        String fileName = selectedFile.getFileName().toString();
        if (encrypt && fileName.endsWith(".enc")){
            alert("This file is already encrypted");
            return;
        }
        
        if(!encrypt && !fileName.endsWith(".enc")){
            alert("Please choose a .enc file to decrypt");
            return;
        }
        
        String warning = encrypt ? "Encryption replaces the original file with a .enc file"
                : "Decrypt this .enc file? Continue?";
        
        if(JOptionPane.showConfirmDialog(this, warning, "Confirm", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE) != JOptionPane.YES_OPTION){
            return;
        }
        
        JPasswordField input = new JPasswordField();
        if (JOptionPane.showConfirmDialog(this, input, "Enter file encryption password", JOptionPane.OK_CANCEL_OPTION) != JOptionPane.OK_OPTION){
            return;
        }
        
        char[] p = input.getPassword();
        
        if(p.length == 0){
            alert("Password cannot be empty.");
            return;
        }
        
        try {
            if(processor != null){
                if(encrypt) {
                    processor.encryptSingleFile(selectedFile, p);
                } else{
                  processor.decryptSingleFile(selectedFile, p);
                } 
                alert("File " + (encrypt ? "encrypted " : "decrypted ") + "succesfully");
                }
                else{
                alert("processor not initialied");
                }
            selectedFile = null;
            jLabel4.setText("No file selected");
            EncryptFileBtn.setVisible(false);
            DecryptFileBtn.setVisible(false);
            
        } catch (Exception ex){
        if(logger != null) logger.logError(ex);
        alert("Operation failed: " + ex.getMessage());
        }finally{
        Arrays.fill(p, '\0');
    } 
    }
    
    private void processFolder(boolean encrypt){
        if (folder == null) {
            alert("Please choose a folder first.");
            return;
        }
        String warning = encrypt ? "Encryption replaces original files with .enc files. Back up the folder before proceeding. Continue?"
                : "Decrypt .enc files in this folder? Continue?";
        if (JOptionPane.showConfirmDialog(this, warning, "Confirm", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE) != JOptionPane.YES_OPTION) {
            return;
        }

        JPasswordField input = new JPasswordField();
        if (JOptionPane.showConfirmDialog(this, input, "Enter folder encryption password", JOptionPane.OK_CANCEL_OPTION) != JOptionPane.OK_OPTION) {
            return;
        }
        char[] p = input.getPassword();
        if (p.length == 0) {
            alert("Password cannot be empty.");
            return;
        }
        try {
            if (processor != null) {
                int count = encrypt ? processor.encryptFolder(folder, p) : processor.decryptFolder(folder, p);
                alert(count + " file(s) " + (encrypt ? "encrypted" : "decrypted") + ". Check the activity log for errors.");
            } else {
                alert("Processor not initialized.");
            }
        } catch (Exception ex) {
            alert("Operation failed: " + ex.getMessage());
        } finally {
            Arrays.fill(p, '\0');
        }
    }
    
    
